# Test the preprocessing script 
def test_run_preprocessing(tmp_path):

    input_file = tmp_path / "input.tsv"
    output_dir = tmp_path / "output"

    # Create realistic test data
    df = create_test_qc_data()

    # Write test data to a temporary TSV
    df.to_csv(
        input_file,
        sep="\t",
        index=False
    )

    # Run the complete preprocessing pipeline
    X_train, X_test = run_preprocessing(
        file_path=input_file,
        out_dir=str(output_dir)
    )

    # Check that outputs are DataFrames
    assert isinstance(X_train, pd.DataFrame)
    assert isinstance(X_test, pd.DataFrame)

    # Train and test must contain the same features
    assert list(X_train.columns) == list(X_test.columns)

    # Check that the split happened correctly
    assert len(X_train) == 16
    assert len(X_test) == 4

    # Check that preprocessing removed missing values
    assert not X_train.isna().any().any()
    assert not X_test.isna().any().any()

    # Check for NaN/inf values
    assert np.isfinite(X_train.values).all()
    assert np.isfinite(X_test.values).all()

    # Check that transformers were saved
    assert (output_dir / "ohe.pkl").exists()
    assert (output_dir / "imputer.pkl").exists()
    assert (output_dir / "scaler.pkl").exists()