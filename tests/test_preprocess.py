# create the test
def create_test_qc_data(n_per_group=5):

    rows = []
    sample_number = 1

    # Create enough samples for stratified train/test splitting
    for sequencer in ["novaseqx", "novaseq6000"]:
        for cancer_type in ["solid_tumour", "haem"]:

            for _ in range(n_per_group):

                row = {
                    "sample_name": f"sample{sample_number}",
                    "sequencer": sequencer,
                    "cancer_type": cancer_type,
                    "fastqc_basic_status": (
                        "pass|pass"
                        if sample_number % 2 == 0
                        else "pass|pass|pass|pass"
                    )
                }

                rows.append(row)
                sample_number += 1

    df = pd.DataFrame(rows)

    # Add all numerical model features required by the pipeline
    for i, feature in enumerate(config.MODEL_FEATURES):

        # These two columns are generated by OneHotEncoder,
        # so they should NOT be present in the raw input.
        if feature.startswith("fastqc_basic_status_"):
            continue

        # Add simple numeric test values
        df[feature] = np.arange(1, len(df) + 1, dtype=float) + i

    return df

# Test the train_test_split
def test_split_test_train():

    df = create_test_qc_data()

    train, test = split_test_train(df)

    assert len(train) == 16
    assert len(test) == 4
    assert set(train.index).isdisjoint(test.index)


